do $$
declare t text;
begin
  foreach t in array array['consorcios','personal','unidades','propietarios','unidad_propietarios','inquilinos',
                           'tipos_reclamo','proveedores','reclamo_proveedores','reclamos','reiteraciones','historial']
  loop
    execute format('alter table public.%I alter column id set generated by default', t);
  end loop;
end $$;

-- Verificación: debe devolver 12 filas con is_generated = BY DEFAULT
select table_name, identity_generation
from information_schema.columns
where table_schema = 'public' and column_name = 'id' and is_identity = 'YES'
order by table_name;
